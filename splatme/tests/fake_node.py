"""
A stand-in for the splat node (node/splatnode.py), for the plugin's tests: the same API, no training. A job
goes through the states in FakeNode.script, one per status request, and stays in the last.
"""
import io
import json
import threading
import zipfile
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import unquote

OPTIONS = {
    "steps": {"min": 1, "max": 200000, "default": 7000},
    "max_gaussians": {"min": 0, "max": 50000000, "default": None},
    "sh_degree": {"min": 1, "max": 3, "default": None},
    "densify_until": {"min": 1000, "max": 200000, "default": None},
}
# A LichtFeld Studio node's, as its /info describes them (node/splatnode.py's LichtFeld.options)
LICHTFELD_OPTIONS = {
    "steps": {"min": 1, "max": 200000, "default": 30000},
    "max_gaussians": {"min": 1000, "max": 50000000, "default": None},
    "sh_degree": {"min": 0, "max": 3, "default": None},
    "strategy": {"choices": ["mrnf", "mcmc", "igs+"], "default": None},
    "exposure_correction": {"type": "bool", "default": None},
    "resume_steps": {"min": 1, "max": 199999, "default": None},
}
MODEL = b"RAD model from the fake node"
# What a node of 0.3.0 says a model needs for it to continue it (node/splatnode.py's SPLAT_PROPERTIES)
SPLAT_PROPERTIES = ["x", "y", "z", "f_dc_0", "f_dc_1", "f_dc_2", "opacity", "scale_0", "scale_1", "scale_2",
                    "rot_0", "rot_1", "rot_2", "rot_3"]


def trained_splats(steps, kind="opensplat", degree=3, leave_out=()):
    """A model's header as the trainers write it (its properties; no splats): OpenSplat's or LichtFeld Studio's."""
    comment = (f"comment Generated by opensplat at iteration {steps}" if kind == "opensplat"
               else f'comment lichtfeld_provenance {{"iteration":{steps}}}')
    rest = [f"f_rest_{i}" for i in range(3 * ((degree + 1) ** 2 - 1))]
    names = ["x", "y", "z", "nx", "ny", "nz", "f_dc_0", "f_dc_1", "f_dc_2", *rest, "opacity", "scale_0", "scale_1",
             "scale_2", "rot_0", "rot_1", "rot_2", "rot_3"]
    lines = ["ply", "format binary_little_endian 1.0", comment, "element vertex 1",
             *(f"property float {name}" for name in names if name not in leave_out), "end_header", ""]
    return "\n".join(lines).encode()


def trained(steps):
    """The model a job of that many steps gives, with OpenSplat's header."""
    return f"ply\ncomment Generated by opensplat at iteration {steps}\nend_header\n".encode()


def trained_lichtfeld(steps):
    """The model a job of a LichtFeld Studio node gives, with its provenance comment."""
    return ('ply\nformat binary_little_endian 1.0\ncomment lichtfeld_provenance {"tool":"LichtFeld Studio",'
            f'"iteration":{steps}}}\nend_header\n').encode()


class FakeNode:
    def __init__(self, token="secret"):
        self.token = token
        self.version = "0.2.0"
        self.options = dict(OPTIONS)  # the options its info lists (an older node has fewer)
        self.trainer_kind = None  # its info's trainer_kind and supports: None, as a node before 0.3.0 says neither
        self.supports = None
        self.continue_from = None  # what a model needs for it to continue it: None, as a node before 0.3.0
        self.splats = None  # (SH degree, properties left out) of the models it gives, with a splat model's header
        self.script = [("queued", {"position": 1}), ("running", {"progress": 50, "step": 5}), ("completed", {})]
        self.failures = []  # statuses its next job status requests answer with a page (a proxy's 502 while the node restarts)
        self.lose_answer = False  # the next new job's answer is lost: the connection closes once the job is made
        self.jobs = {}  # id -> {"options", "names" (the zip's files), "resume" (the model it continues), "asked" (status requests), "deleted"}
        node = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args):
                pass

            def send(self, status, body, headers=None):
                data = body if isinstance(body, bytes) else json.dumps(body).encode()
                self.send_response(status)
                self.send_header("Content-Length", str(len(data)))
                for name, value in (headers or {}).items():
                    self.send_header(name, value)
                self.end_headers()
                self.wfile.write(data)

            def handle_request(self):
                length = int(self.headers.get("Content-Length") or 0)
                body = self.rfile.read(length) if length else b""
                if self.headers.get("Authorization") != "Bearer " + node.token:
                    return self.send(401, {"error": "Wrong or missing token"})
                path, _, query = self.path.partition("?")
                parts = [p for p in path.split("/") if p]
                if parts == ["info"]:
                    return self.send(200, node.info())
                params = dict(pair.split("=") for pair in query.split("&") if pair)
                if parts == ["jobs"] and self.command == "GET":
                    found = [node.describe(i) for i, j in node.jobs.items() if j.get("ref") == params.get("ref")]
                    return self.send(200, found)
                if parts == ["jobs"] and self.command == "POST":
                    job_id = f"job{len(node.jobs) + 1}"
                    ref = params.pop("ref", None)
                    unknown = [k for k in params if k not in node.options]
                    if unknown:  # as the node refuses an option its trainer does not have
                        return self.send(400, {"error": f"Unknown option: {unknown[0]}"})
                    options = {k: int(v) if v.isdigit() else {"True": True, "False": False}.get(v, unquote(v))
                               for k, v in params.items()}
                    with zipfile.ZipFile(io.BytesIO(body)) as z:
                        names = z.namelist()
                        resume = z.read("resume.ply") if "resume.ply" in names else None
                        masks = {name: z.read(name) for name in names if name.startswith("masks/")}
                    node.jobs[job_id] = {
                        "options": options, "names": names, "resume": resume, "masks": masks, "asked": 0, "deleted": False,
                        "ref": ref,
                    }  # fmt: skip
                    if node.lose_answer:
                        node.lose_answer = False
                        self.close_connection = True
                        return None
                    return self.send(201, node.describe(job_id))
                job = node.jobs.get(parts[1]) if len(parts) > 1 and parts[0] == "jobs" else None
                if job is None or job["deleted"]:
                    return self.send(404, {"error": "No such job"})
                if len(parts) == 2 and self.command == "DELETE":
                    job["deleted"] = True
                    return self.send(200, {})
                if len(parts) == 2 and node.failures:
                    status = node.failures.pop(0)
                    return self.send(status, b"<html>Bad Gateway</html>")
                if len(parts) == 2:
                    job["asked"] += 1
                    return self.send(200, node.describe(parts[1]))
                if parts[2] == "log":
                    return self.send(200, b"Step 10: 0.5 [100%]\n", {"X-Log-Offset": "20"})
                if parts[2] == "result":
                    if node.splats is not None:
                        return self.send(200, trained_splats(job["options"]["steps"], node.trainer_kind or "opensplat",
                                                             *node.splats))
                    made = trained_lichtfeld if node.trainer_kind == "lichtfeld" else trained
                    return self.send(200, made(job["options"]["steps"]))
                return self.send(404, {"error": "Not found"})

            do_GET = do_POST = do_DELETE = handle_request

        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.url = f"http://127.0.0.1:{self.server.server_address[1]}"
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    def run_lichtfeld(self):
        """Makes it a LichtFeld Studio node: its kind, what it supports and its options."""
        self.trainer_kind, self.supports, self.options = "lichtfeld", {"masks": True, "continue": True}, dict(LICHTFELD_OPTIONS)

    def run_030(self, kind="opensplat", degree=3):
        """Makes it a node of 0.3.0 with that trainer: it says what a model needs to be continued, and its models
        have a splat model's header (of that SH degree)."""
        if kind == "lichtfeld":
            self.run_lichtfeld()
        else:
            self.trainer_kind, self.supports = "opensplat", {"masks": True, "continue": True}
            self.options = {**OPTIONS, "resume_steps": {"min": 1, "max": 199999, "default": None}}
        self.version = "0.3.0"
        self.continue_from = {"properties": SPLAT_PROPERTIES, "sh_degrees": [0, 1, 2, 3] if kind == "lichtfeld" else [1, 2, 3]}
        self.splats = (degree, ())

    def info(self):
        info = {
            "name": "SplatMe splat node", "version": self.version, "trainer": "OpenSplat fake",
            "gpu": {"name": "Fake GPU"}, "running": None, "queued": 0, "options": self.options,
        }  # fmt: skip
        if self.trainer_kind is not None:
            info["trainer_kind"] = self.trainer_kind
        if self.supports is not None:
            info["supports"] = self.supports
        if self.continue_from is not None:
            info["continue_from"] = self.continue_from
        return info

    def describe(self, job_id):
        job = self.jobs[job_id]
        state, more = self.script[min(max(job["asked"] - 1, 0), len(self.script) - 1)]
        return {"id": job_id, "state": state, "options": job["options"], "error": None, **more}

    def add_job(self, job_id="job-known"):
        """A job the node already has, as after a worker lost track of it."""
        self.jobs[job_id] = {"options": {"steps": 10}, "names": [], "resume": None, "asked": 0, "deleted": False}
        return job_id

    def close(self):
        self.server.shutdown()
        self.server.server_close()
